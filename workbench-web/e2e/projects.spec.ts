import {test,expect} from '@playwright/test'
test('create real project, edit files, inspect syntax and persist',async({page})=>{
 await page.goto('/')
 await page.getByLabel('项目名称',{exact:true}).fill('校园工具测试')
 await page.getByRole('button',{name:'新建项目',exact:true}).click()
 await page.getByRole('textbox',{name:'Python 代码'}).fill('def custom(:\n    pass')
 await expect(page.getByText('发现 Python 语法错误；',{exact:false})).toBeVisible()
 await page.getByRole('textbox',{name:'Python 代码'}).fill('def custom():\n    return 42\n')
 await expect(page.getByText('Python 语法检查通过。',{exact:false})).toBeVisible()
 await page.getByLabel('新文件路径').fill('lib/helper.py')
 await page.getByRole('button',{name:'添加文件'}).click()
 await page.getByRole('textbox',{name:'Python 代码'}).fill('value = 7\n')
 await page.getByRole('button',{name:'保存项目',exact:true}).click()
 await expect(page.getByText('已保存到服务端 · 版本 1')).toBeVisible()
 await page.reload()
 await page.getByLabel('打开项目').selectOption({label:'校园工具测试'})
 await page.getByRole('button',{name:'lib/helper.py',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Python 代码'})).toHaveText('value = 7')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
