test('late project settings save preserves code typed after submission',async({page})=>{
 await page.setViewportSize({width:1440,height:900});await page.goto('/')
 await page.getByRole('button',{name:'体验示例',exact:true}).click()
 let release!:()=>void;const gate=new Promise<void>(r=>release=r);let started=false
 await page.route('**/api/projects/*',async route=>{
  if(route.request().method()!=='POST'||!route.request().postDataJSON()?.name)return route.continue()
  const response=await route.fetch();started=true;await gate;await route.fulfill({response})
 })
 await page.locator('.project-picker').click();await page.getByRole('menuitem',{name:'项目设置'}).click()
 await page.getByLabel('项目名称',{exact:true}).fill('新的项目名称');await page.getByRole('button',{name:'保存设置'}).click()
 await expect.poll(()=>started).toBe(true)
 await page.getByRole('dialog').getByRole('button',{name:'取消'}).click()
 await editCode(page,'draft = 123')
 release()
 await expect(page.getByRole('heading',{name:'新的项目名称',exact:true})).toBeVisible()
 await expect(page.getByRole('textbox',{name:'Python 代码'})).toHaveText('draft = 123')
 await expect(page.getByRole('button',{name:'保存项目',exact:true})).toBeEnabled()
})
