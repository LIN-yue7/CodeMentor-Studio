test('project menu creates through a closing dialog and restores the last opened file',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'新建项目',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'新建项目',exact:true})
 await dialog.getByLabel('项目名称',{exact:true}).fill('R7 导航项目')
 await dialog.getByRole('button',{name:'创建项目',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 if(await page.getByRole('button',{name:'文件面板'}).isVisible())await page.getByRole('button',{name:'文件面板'}).click()
 await page.getByRole('button',{name:'新建文件',exact:true}).click()
 await page.getByRole('dialog').getByLabel('文件路径').fill('lib/helper.py')
 await page.getByRole('dialog').getByRole('button',{name:'创建文件'}).click()
 await editCode(page,'value = 42\n')
 await page.getByRole('button',{name:'保存项目',exact:true}).click()
 await expect(page.getByText('已保存到服务端 · 版本 1')).toBeVisible()
 await page.reload()
 await expect(page.getByRole('textbox',{name:'Python 代码'})).toHaveText('value = 42')
 await expect(page.getByRole('tab',{name:'lib/helper.py',exact:true})).toHaveAttribute('aria-selected','true')
})

